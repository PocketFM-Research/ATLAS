def entry(
    original: str,
    replacement: str,
    kind: str,
    variants: list[str] | None = None,
    variant_replacements: list[str] | None = None,
) -> dict:
    variants = variants or []
    variant_replacements = variant_replacements or []
    if len(variants) != len(variant_replacements):
        raise ValueError(f"Variant length mismatch for {original}")
    return {
        "original": original,
        "replacement": replacement,
        "type": kind,
        "variants": variants,
        "variant_replacements": variant_replacements,
    }


