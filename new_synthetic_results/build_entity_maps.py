def story_dirs() -> list[Path]:
    return sorted(path.parent for path in ROOT.glob("*/*/*/cleaned.txt"))


def main() -> None:
    written = 0
    for story_dir in story_dirs():
        slug = story_dir.name
        metadata = json.loads((story_dir / "metadata.json").read_text(encoding="utf-8"))
        mappings = MAPS.get(slug)
        if mappings is None:
            raise KeyError(f"No entity map spec for {slug}")
        replacements = [item["replacement"] for item in mappings]
        duplicates = sorted({item for item in replacements if replacements.count(item) > 1})
        if duplicates:
            raise ValueError(f"Duplicate replacements in {slug}: {duplicates}")
        payload = {
            "story_id": metadata.get("document_id") or slug,
            "mappings": mappings,
        }
        (story_dir / "entity_map.json").write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        written += 1
    print(f"Wrote {written} entity_map.json files")


if __name__ == "__main__":
    main()
